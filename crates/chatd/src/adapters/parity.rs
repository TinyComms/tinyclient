//! The network ceiling, printed from the capability constructors the adapters already use.
//! `chatd --capabilities` writes this. `docs/parity.md` is that print, checked in so a review
//! can see it. A hand-edited table fails the test below.

use protocol::{CallOffer, ConversationKind, Network};

const MISSING: &str = "\u{2013}";

/// Column order is the one the product table uses. [`Network::ALL`] is a different order.
const ORDER: [Network; 7] = [
    Network::Discord,
    Network::Slack,
    Network::Telegram,
    Network::Teams,
    Network::Signal,
    Network::Messages,
    Network::Tiny,
];

#[derive(Clone, Copy, PartialEq, Eq)]
enum Audio {
    Direct,
    Group,
    Room,
    Stage,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Mark {
    Native,
    Handoff,
    Missing,
    Absent,
}

/// Markdown for the ceiling. The same string `docs/parity.md` must hold.
pub fn markdown() -> String {
    let mut out = String::new();
    out.push_str("# What works on each network\n\n");
    out.push_str("Generated by `chatd --capabilities` from the capability ceiling each adapter already reports. ");
    out.push_str("The ceiling is what that network can do, not one account's plan. ");
    out.push_str(&format!("**N** is native, **H** opens the official app, **{MISSING}** is missing, and **n/a** means the network has no such thing. "));
    out.push_str(&format!("A {MISSING} or H cell links to an issue when the generator has one for that gap. "));
    out.push_str("Typing indicators and read receipts are not rows: no capability flag says whether this client sends them. ");
    out.push_str("Do not edit this file by hand.\n\n");
    out.push_str("## Calls\n\n");
    out.push_str(&table(&call_rows()));
    out.push_str("\n## Messaging\n\n");
    out.push_str(&table(&message_rows()));
    out
}

fn ceiling(network: Network) -> protocol::Capabilities {
    match network {
        Network::Discord => super::discord::capability_ceiling(),
        Network::Slack => super::slack::capability_ceiling(),
        Network::Telegram => super::telegram::capability_ceiling(),
        Network::Teams => super::teams::capability_ceiling(),
        Network::Signal => super::signal::capability_ceiling(),
        Network::Messages => super::messages::capability_ceiling(),
        Network::Tiny => super::tiny::capability_ceiling(),
    }
}

/// The call button the adapter's own row constructor would set for this kind.
fn offer(network: Network, kind: Audio) -> CallOffer {
    use Audio::*;
    match (network, kind) {
        (Network::Discord, Direct | Group) => super::discord::private_call(false).into(),
        (Network::Discord, Room) => super::discord::voice_channel_call().into(),
        (Network::Discord, Stage) => super::discord::stage_channel_call().into(),
        // Slack has no stage. Every conversation it does place can hold a huddle.
        (Network::Slack, Stage) => CallOffer::Absent,
        (Network::Slack, _) => super::slack::call_support().into(),
        (Network::Telegram, Direct) => super::telegram::direct_call_ceiling().into(),
        (Network::Telegram, Group | Room) => super::telegram::other_call().into(),
        (Network::Telegram, Stage) => CallOffer::Absent,
        (Network::Teams, Direct | Group) => super::teams::chat_call(false, false).into(),
        (Network::Teams, Room) => super::teams::channel_call().into(),
        (Network::Teams, Stage) => CallOffer::Absent,
        (Network::Signal, Direct) => super::signal::call_offer(ConversationKind::Direct),
        (Network::Signal, Group) => super::signal::call_offer(ConversationKind::Group),
        (Network::Signal, Room) => super::signal::call_offer(ConversationKind::Voice),
        (Network::Signal, Stage) => CallOffer::Absent,
        (Network::Messages, Direct) => super::messages::offered_call(false, false, false, true),
        (Network::Messages, Group) => super::messages::offered_call(true, false, false, false),
        (Network::Messages, Room | Stage) => CallOffer::Absent,
        (Network::Tiny, Direct) => super::tiny::direct_call(true).into(),
        (Network::Tiny, Group) => super::tiny::group_offer(),
        (Network::Tiny, Room) => super::tiny::room_call().into(),
        (Network::Tiny, Stage) => CallOffer::Absent,
    }
}

fn mark_of(offer: CallOffer) -> Mark {
    match offer {
        CallOffer::Native => Mark::Native,
        CallOffer::Handoff => Mark::Handoff,
        CallOffer::Missing => Mark::Missing,
        CallOffer::Absent => Mark::Absent,
    }
}

fn flag(on: bool) -> Mark {
    if on { Mark::Native } else { Mark::Missing }
}

/// A reply that is really a thread (Slack) is not a missing quote.
fn quote(network: Network) -> Mark {
    let caps = ceiling(network);
    if caps.reply {
        Mark::Native
    } else if caps.threads {
        Mark::Absent
    } else {
        Mark::Missing
    }
}

/// Camera and screen share follow the pictures predicate and whatever call this network already places.
fn pictures(network: Network) -> Mark {
    let placed = [Audio::Direct, Audio::Group, Audio::Room].map(|kind| offer(network, kind));
    if protocol::call_pictures(network) && placed.iter().any(|offer| *offer == CallOffer::Native) {
        Mark::Native
    } else if placed.iter().any(|offer| *offer == CallOffer::Handoff) {
        Mark::Handoff
    } else if placed.iter().all(|offer| *offer == CallOffer::Absent) {
        Mark::Absent
    } else {
        Mark::Missing
    }
}

/// We ring here only when the direct call itself is native.
fn ring(network: Network) -> Mark {
    match offer(network, Audio::Direct) {
        CallOffer::Native => Mark::Native,
        CallOffer::Absent => Mark::Absent,
        CallOffer::Handoff | CallOffer::Missing => Mark::Missing,
    }
}

fn call_rows() -> Vec<(String, Vec<String>)> {
    vec![
        row("Direct audio", |network| mark_of(offer(network, Audio::Direct))),
        row("Group audio", |network| mark_of(offer(network, Audio::Group))),
        row("Room or channel audio", |network| mark_of(offer(network, Audio::Room))),
        row("Stage", |network| mark_of(offer(network, Audio::Stage))),
        row("Camera", pictures),
        row("Screen share", pictures),
        row("Ring a direct call", ring),
    ]
}

fn message_rows() -> Vec<(String, Vec<String>)> {
    vec![
        row("Reactions", |network| flag(ceiling(network).reactions)),
        row("Quote reply", quote),
        row("Threads", |network| flag(ceiling(network).threads)),
        row("Edit own message", |network| flag(ceiling(network).edit)),
        row("Delete own message", |network| flag(ceiling(network).delete)),
        row("Pins", |network| flag(ceiling(network).pins)),
        row("Search this conversation", |network| flag(ceiling(network).search)),
        row("Search everywhere", |network| flag(ceiling(network).search_global)),
        row("Send files", |network| flag(ceiling(network).max_file_bytes > 0)),
        row("GIF search", |network| flag(ceiling(network).gifs)),
        row("Stickers", |network| flag(ceiling(network).stickers)),
        row("Voice message", |network| flag(ceiling(network).voice_notes)),
        row("Schedule send", |network| flag(ceiling(network).schedule)),
        row("Forward", |network| flag(ceiling(network).forward)),
        row("Polls", |network| flag(ceiling(network).polls.is_some())),
        row("Link previews", |network| flag(ceiling(network).suppress_embeds)),
        row("Mentions", |network| flag(!ceiling(network).mention_format.is_plain() || ceiling(network).mention_spans)),
        row("Set a status", |network| flag(ceiling(network).presence_status || ceiling(network).rich_status)),
        row("Translate", |network| flag(ceiling(network).translate)),
    ]
}

fn row(label: &str, cell: impl Fn(Network) -> Mark) -> (String, Vec<String>) {
    let cells = ORDER.iter().copied().map(|network| show(cell(network), label, network)).collect();
    (label.to_owned(), cells)
}

fn show(mark: Mark, label: &str, network: Network) -> String {
    let word = match mark {
        Mark::Native => "N",
        Mark::Handoff => "H",
        Mark::Missing => MISSING,
        Mark::Absent => "n/a",
    };
    if mark == Mark::Native {
        return word.to_owned();
    }
    // A link is printed only for a gap. It is not a second copy of the cell.
    match gap(label, network) {
        Some(number) => format!("{word} ([#{number}](https://github.com/TinyComms/tinyclient/issues/{number}))"),
        None => word.to_owned(),
    }
}

fn gap(label: &str, network: Network) -> Option<u32> {
    match (label, network) {
        ("Group audio", Network::Tiny) => Some(291),
        _ => None,
    }
}

fn table(rows: &[(String, Vec<String>)]) -> String {
    let mut lines = vec![header(), rule()];
    for (label, cells) in rows {
        lines.push(format!("| {label} | {} |", cells.join(" | ")));
    }
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

fn header() -> String {
    let names: Vec<&str> = ORDER.iter().copied().map(Network::label).collect();
    format!("| | {} |", names.join(" | "))
}

fn rule() -> String {
    let cells = std::iter::repeat_n("---", ORDER.len() + 1);
    format!("| {} |", cells.collect::<Vec<_>>().join(" | "))
}

#[cfg(test)]
mod tests {
    use super::markdown;

    #[test]
    fn committed_table_matches_the_generator() {
        assert_eq!(markdown(), include_str!("../../../../docs/parity.md"));
    }

    #[test]
    fn teams_cannot_send_files() {
        assert_eq!(super::super::teams::capability_ceiling().max_file_bytes, 0);
        let row = markdown().lines().find(|line| line.starts_with("| Send files |")).expect("send files row");
        let cells = cells(row);
        assert_eq!(cells[4], "\u{2013}");
    }

    #[test]
    fn discord_reactions_are_native() {
        assert!(super::super::discord::capability_ceiling().reactions);
        let row = markdown().lines().find(|line| line.starts_with("| Reactions |")).expect("reactions row");
        assert_eq!(cells(row)[1], "N");
    }

    #[test]
    fn native_cells_are_not_issue_links() {
        let text = markdown();
        assert!(!text.contains("N ([#"));
        assert!(text.contains("[#291](https://github.com/TinyComms/tinyclient/issues/291)"));
    }

    fn cells(row: &str) -> Vec<&str> {
        row.trim_matches('|').split('|').map(str::trim).filter(|cell| !cell.is_empty()).collect()
    }
}
