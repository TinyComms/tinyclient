//! AV1 as Discord carries it: RTP Payload Format for AV1 (§5 aggregation header) depacketizer,
//! OBU temporal unit reassembly, and pure-Rust AV1 decoding (`rusty_av1d`, no-asm build).
//!
//! Each AV1 RTP packet begins with a 1-byte aggregation header (`Z | Y | W(2) | N | 000`) followed
//! by one or more OBU elements (or fragments). On the wire, OBU elements omit `obu_size`
//! (`obu_has_size_field = 0`). When reassembling a temporal unit for DAVE decryption and decoding,
//! every OBU except the last has `obu_has_size_field` set with its LEB128 payload size, while the
//! last OBU keeps `obu_has_size_field = 0` so a DAVE supplemental footer sits directly after the
//! final OBU payload (matching `davey`'s `process_frame_av1`).

use crate::picture::Planes;
use rusty_av1d::rust_api::{Decoder, PixelLayout, PlanarImageComponent, Settings};
use rusty_av1d::Rav1dError;

/// The most bytes of AV1 payload one packet carries in tests.
pub const MAX_PAYLOAD: usize = 1000;

const OBU_HEADER_HAS_EXTENSION: u8 = 0b0_0000_100;
const OBU_HEADER_HAS_SIZE: u8 = 0b0_0000_010;
const OBU_HEADER_TYPE_MASK: u8 = 0b0_1111_000;
const OBU_TYPE_SEQUENCE_HEADER: u8 = 1;
const OBU_TYPE_TEMPORAL_DELIMITER: u8 = 2;
const OBU_TYPE_FRAME_HEADER: u8 = 3;
const OBU_TYPE_FRAME: u8 = 6;
const OBU_TYPE_TILE_LIST: u8 = 8;
const OBU_TYPE_PADDING: u8 = 15;

/// Genuine 64×48 solid-color AV1 keyframe temporal unit (Sequence Header + Frame OBU, 33 bytes,
/// generated by libaom-av1). Used by tests and E2E proofs without needing an AV1 encoder crate.
pub const SAMPLE_KEYFRAME_OBU: &[u8] = &[
    0x0a, 0x0a, 0x00, 0x00, 0x00, 0x02, 0xaf, 0xf7, 0x9b, 0x5f, 0x20, 0x08, 0x32, 0x13, 0x10, 0x00,
    0xc0, 0x00, 0x00, 0x02, 0x80, 0x00, 0x00, 0x0a, 0x05, 0xb2, 0x53, 0x2a, 0x43, 0x11, 0x14, 0x95,
    0x20,
];

/// One RTP packet of an AV1 temporal unit.
#[derive(Debug, PartialEq, Eq)]
pub struct Piece {
    pub payload: Vec<u8>,
    pub marker: bool,
}

/// Parsed AV1 RTP aggregation header (RTP Payload Format for AV1 §5).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AggregationHeader {
    /// First OBU element continues an OBU fragment from the previous packet.
    pub z: bool,
    /// Last OBU element continues into the next packet.
    pub y: bool,
    /// Number of OBU elements in this packet (0 means arbitrary count, all length-prefixed).
    pub w: u8,
    /// First packet of a coded video sequence (starts with a sequence header / keyframe).
    pub n: bool,
}

/// Reads an AV1 unsigned LEB128 integer (up to 8 bytes, §4.10.5). Returns `(value, bytes_read)`.
pub fn read_leb128(data: &[u8]) -> Option<(usize, usize)> {
    let mut value = 0u64;
    for (i, &byte) in data.iter().take(8).enumerate() {
        value |= u64::from(byte & 0x7f) << (i * 7);
        if byte & 0x80 == 0 {
            let val = usize::try_from(value).ok()?;
            return Some((val, i + 1));
        }
    }
    None
}

/// Writes `value` as unsigned LEB128 into `out`.
pub fn write_leb128(mut value: usize, out: &mut Vec<u8>) {
    loop {
        let mut byte = (value & 0x7f) as u8;
        value >>= 7;
        if value != 0 {
            byte |= 0x80;
        }
        out.push(byte);
        if value == 0 {
            break;
        }
    }
}

/// Parses one AV1 RTP payload into its aggregation header and raw OBU element slices.
pub fn parse_packet(payload: &[u8]) -> Option<(AggregationHeader, Vec<&[u8]>)> {
    let hdr = *payload.first()?;
    let agg = AggregationHeader {
        z: hdr & 0x80 != 0,
        y: hdr & 0x40 != 0,
        w: (hdr >> 4) & 0x03,
        n: hdr & 0x08 != 0,
    };
    let mut at = 1usize;
    let mut elements = Vec::new();
    if agg.w == 0 {
        while at < payload.len() {
            let (len, nbytes) = read_leb128(&payload[at..])?;
            at += nbytes;
            if at + len > payload.len() {
                return None;
            }
            elements.push(&payload[at..at + len]);
            at += len;
        }
    } else {
        for idx in 0..agg.w {
            let is_last = idx + 1 == agg.w;
            if is_last {
                if at > payload.len() {
                    return None;
                }
                elements.push(&payload[at..]);
                at = payload.len();
            } else {
                let (len, nbytes) = read_leb128(&payload[at..])?;
                at += nbytes;
                if at + len > payload.len() {
                    return None;
                }
                elements.push(&payload[at..at + len]);
                at += len;
            }
        }
    }
    if elements.is_empty() {
        return None;
    }
    Some((agg, elements))
}

/// Walks OBUs in a size-delimited (or last-OBU-unbounded) AV1 temporal unit.
/// Each returned item is `(obu_header_byte, optional_extension_byte, payload_slice)`.
pub fn parse_obus(frame: &[u8]) -> Option<Vec<(u8, Option<u8>, &[u8])>> {
    let mut at = 0usize;
    let mut out = Vec::new();
    while at < frame.len() {
        let header = frame[at];
        at += 1;
        let has_ext = header & OBU_HEADER_HAS_EXTENSION != 0;
        let has_size = header & OBU_HEADER_HAS_SIZE != 0;
        let ext = if has_ext {
            let b = *frame.get(at)?;
            at += 1;
            Some(b)
        } else {
            None
        };
        let size = if has_size {
            let (len, nbytes) = read_leb128(&frame[at..])?;
            at += nbytes;
            len
        } else {
            frame.len() - at
        };
        if at + size > frame.len() {
            return None;
        }
        out.push((header, ext, &frame[at..at + size]));
        at += size;
    }
    Some(out)
}

/// True when `frame` contains a Sequence Header OBU (type 1) or a keyframe header.
pub fn is_key(frame: &[u8]) -> bool {
    let Some(obus) = parse_obus(frame) else {
        return false;
    };
    for (header, _ext, payload) in obus {
        let obu_type = (header & OBU_HEADER_TYPE_MASK) >> 3;
        if obu_type == OBU_TYPE_SEQUENCE_HEADER {
            return true;
        }
        if matches!(obu_type, OBU_TYPE_FRAME_HEADER | OBU_TYPE_FRAME) && !payload.is_empty() {
            // Uncompressed frame header: show_existing_frame (bit 7) == 0, frame_type (bits 6..5) == 0 (KEY_FRAME).
            if (payload[0] & 0xe0) == 0 {
                return true;
            }
        }
    }
    false
}

/// Serializes assembled raw OBU elements (where `obu_has_size_field` may be 0) into a temporal unit
/// suitable for DAVE decryption: every non-last OBU carries `obu_has_size_field = 1` + LEB128
/// payload length, and the last OBU keeps `obu_has_size_field = 0` so any trailing DAVE
/// supplemental footer remains attached to the final OBU.
fn assemble_temporal_unit(obus: &[Vec<u8>]) -> Vec<u8> {
    let mut out = Vec::new();
    let last = obus.len().saturating_sub(1);
    for (idx, obu) in obus.iter().enumerate() {
        if obu.is_empty() {
            continue;
        }
        let header = obu[0];
        let has_ext = header & OBU_HEADER_HAS_EXTENSION != 0;
        let has_size = header & OBU_HEADER_HAS_SIZE != 0;
        let header_len = 1 + usize::from(has_ext);
        if obu.len() < header_len {
            continue;
        }
        if idx < last {
            if has_size {
                out.extend_from_slice(obu);
            } else {
                out.push(header | OBU_HEADER_HAS_SIZE);
                if has_ext {
                    out.push(obu[1]);
                }
                let payload_len = obu.len() - header_len;
                write_leb128(payload_len, &mut out);
                out.extend_from_slice(&obu[header_len..]);
            }
        } else {
            // Keep the last OBU as received (typically has_size = 0, matching davey's framing).
            out.extend_from_slice(obu);
        }
    }
    out
}

/// Ensures every OBU in `frame` has `obu_has_size_field = 1` + LEB128 length and prepends a
/// temporal delimiter so `rusty_av1d` can decode a single temporal unit immediately.
fn normalize_for_decoder(frame: &[u8]) -> Option<Vec<u8>> {
    let obus = parse_obus(frame)?;
    let mut out = Vec::with_capacity(frame.len() + 16);
    let has_td = obus
        .first()
        .is_some_and(|(h, _, _)| ((h & OBU_HEADER_TYPE_MASK) >> 3) == OBU_TYPE_TEMPORAL_DELIMITER);
    if !has_td {
        out.extend_from_slice(&[0x12, 0x00]);
    }
    for (header, ext, payload) in obus {
        out.push(header | OBU_HEADER_HAS_SIZE);
        if let Some(ext) = ext {
            out.push(ext);
        }
        write_leb128(payload.len(), &mut out);
        out.extend_from_slice(payload);
    }
    Some(out)
}

/// Splits one AV1 temporal unit (clear or DAVE-sealed) into AV1 RTP packets (RTP Payload Format
/// for AV1 §5). Strips `obu_size` on wire elements so depacketization reproduces the exact
/// DAVE-sealed frame bytes.
pub fn packetize(frame: &[u8], max_payload: usize) -> Vec<Piece> {
    let Some(obus) = parse_obus(frame) else {
        return Vec::new();
    };
    // Filter out temporal delimiter / tile list / padding OBUs that RTP packetizers drop, and strip
    // obu_size on wire OBU elements (setting has_size = 0).
    let mut wire_obus: Vec<Vec<u8>> = Vec::new();
    let mut starts_cvs = false;
    for (header, ext, payload) in obus {
        let obu_type = (header & OBU_HEADER_TYPE_MASK) >> 3;
        if matches!(obu_type, OBU_TYPE_TEMPORAL_DELIMITER | OBU_TYPE_TILE_LIST | OBU_TYPE_PADDING) {
            continue;
        }
        if obu_type == OBU_TYPE_SEQUENCE_HEADER {
            starts_cvs = true;
        }
        let mut elem = Vec::with_capacity(2 + payload.len());
        elem.push(header & !OBU_HEADER_HAS_SIZE);
        if let Some(ext) = ext {
            elem.push(ext);
        }
        elem.extend_from_slice(payload);
        wire_obus.push(elem);
    }
    if wire_obus.is_empty() {
        return Vec::new();
    }

    let max_body = max_payload.saturating_sub(1).max(1);
    let mut pieces = Vec::new();
    let mut first_packet = true;

    // Pack OBUs; if an OBU fits in one packet (possibly aggregated with others), pack it, otherwise
    // fragment it cleanly across packets with Y/Z flags.
    let mut idx = 0usize;
    while idx < wire_obus.len() {
        let obu = &wire_obus[idx];
        if obu.len() > max_body {
            // Fragment this OBU across multiple packets with W=1.
            let mut off = 0usize;
            while off < obu.len() {
                let take = (obu.len() - off).min(max_body);
                let z = off > 0;
                let y = off + take < obu.len();
                let n = first_packet && starts_cvs;
                first_packet = false;
                let hdr = (u8::from(z) << 7) | (u8::from(y) << 6) | (1 << 4) | (u8::from(n) << 3);
                let mut payload = Vec::with_capacity(1 + take);
                payload.push(hdr);
                payload.extend_from_slice(&obu[off..off + take]);
                off += take;
                pieces.push(Piece { payload, marker: false });
            }
            idx += 1;
            continue;
        }

        // Aggregate as many small OBUs as fit (up to W=3 so the last needs no length prefix).
        let mut batch: Vec<&[u8]> = Vec::new();
        let mut used = 0usize;
        while idx < wire_obus.len() && batch.len() < 3 {
            let candidate = &wire_obus[idx];
            // Overhead for previous element's LEB128 length when another element follows.
            let prev_overhead = batch.last().map_or(0, |prev| leb128_len(prev.len()));
            if !batch.is_empty() && used + prev_overhead + candidate.len() > max_body {
                break;
            }
            used += prev_overhead + candidate.len();
            batch.push(candidate);
            idx += 1;
        }
        let w = batch.len() as u8;
        let n = first_packet && starts_cvs;
        first_packet = false;
        let hdr = (w << 4) | (u8::from(n) << 3);
        let mut payload = Vec::with_capacity(1 + used);
        payload.push(hdr);
        for (i, elem) in batch.iter().enumerate() {
            if i + 1 < batch.len() {
                write_leb128(elem.len(), &mut payload);
            }
            payload.extend_from_slice(elem);
        }
        pieces.push(Piece { payload, marker: false });
    }
    if let Some(last) = pieces.last_mut() {
        last.marker = true;
    }
    pieces
}

fn leb128_len(mut value: usize) -> usize {
    let mut n = 1;
    while value >= 0x80 {
        value >>= 7;
        n += 1;
    }
    n
}

/// Rebuilds whole AV1 temporal units from RTP packets of one SSRC in sequence order.
#[derive(Debug, Default)]
pub struct Assembler {
    timestamp: Option<u32>,
    next: Option<u16>,
    obus: Vec<Vec<u8>>,
    frag: Vec<u8>,
    frag_open: bool,
    /// A packet was lost. Nothing is emitted until a new coded video sequence (`N=1` or Sequence
    /// Header OBU) begins.
    broken: bool,
}

impl Assembler {
    /// Pushes one RTP packet. Returns `Some(frame)` when the marker bit closes a complete,
    /// contiguous AV1 temporal unit.
    pub fn push(&mut self, sequence: u16, timestamp: u32, marker: bool, payload: &[u8]) -> Option<Vec<u8>> {
        let (agg, elements) = parse_packet(payload)?;
        let other_time = self.timestamp.is_some_and(|held| held != timestamp);
        let gap = self.next.is_some_and(|next| next != sequence);
        if other_time || gap {
            self.obus.clear();
            self.frag.clear();
            self.frag_open = false;
            if gap {
                self.broken = true;
            }
        }
        self.timestamp = Some(timestamp);
        self.next = Some(sequence.wrapping_add(1));

        let starts_seq = agg.n
            || (!agg.z
                && elements
                    .first()
                    .and_then(|e| e.first())
                    .is_some_and(|h| ((h & OBU_HEADER_TYPE_MASK) >> 3) == OBU_TYPE_SEQUENCE_HEADER));
        if self.broken {
            if starts_seq && !agg.z {
                self.broken = false;
            } else {
                return None;
            }
        }

        let last_idx = elements.len() - 1;
        for (idx, elem) in elements.iter().enumerate() {
            let continues_prev = idx == 0 && agg.z;
            let continues_next = idx == last_idx && agg.y;

            if continues_prev {
                if !self.frag_open {
                    self.reset_broken();
                    return None;
                }
                self.frag.extend_from_slice(elem);
                if !continues_next {
                    self.frag_open = false;
                    self.obus.push(std::mem::take(&mut self.frag));
                }
            } else {
                if self.frag_open {
                    self.reset_broken();
                    return None;
                }
                if continues_next {
                    self.frag.clear();
                    self.frag.extend_from_slice(elem);
                    self.frag_open = true;
                } else if !elem.is_empty() {
                    self.obus.push(elem.to_vec());
                }
            }
        }

        if marker {
            if self.frag_open || self.obus.is_empty() {
                self.reset_broken();
                return None;
            }
            let frame = assemble_temporal_unit(&self.obus);
            self.obus.clear();
            self.timestamp = None;
            return (!frame.is_empty()).then_some(frame);
        }
        None
    }

    fn reset_broken(&mut self) {
        self.obus.clear();
        self.frag.clear();
        self.frag_open = false;
        self.broken = true;
    }
}

/// Pure-Rust AV1 decoder (`rusty_av1d`, no-asm build), converting each decoded 8-bit frame into
/// packed I420 [`Planes`] for `picture::rgb`.
pub struct Av1Decoder {
    inner: Decoder,
}

impl Av1Decoder {
    pub fn new() -> Result<Self, ()> {
        let mut settings = Settings::new();
        settings.set_n_threads(1);
        settings.set_max_frame_delay(1);
        settings.set_apply_grain(false);
        // Guard against absurd headers (4K ceiling).
        settings.set_frame_size_limit(3840 * 2160);
        let inner = Decoder::with_settings(&settings).map_err(|_| ())?;
        Ok(Self { inner })
    }

    /// Decodes one AV1 temporal unit (clear OBU bitstream). Returns `Ok(None)` when the decoder
    /// buffers without producing a displayable frame yet, `Ok(Some(planes))` on output, and
    /// `Err(())` on corrupt input.
    #[allow(clippy::result_unit_err)]
    pub fn decode(&mut self, frame: &[u8]) -> Result<Option<Planes>, ()> {
        let normalized = normalize_for_decoder(frame).ok_or(())?;
        match self.inner.send_data(normalized.into_boxed_slice(), None, None, None) {
            Ok(()) => {}
            Err(Rav1dError::TryAgain) => {
                let _ = self.inner.get_picture();
                self.inner.send_pending_data().map_err(|_| ())?;
            }
            Err(_) => return Err(()),
        }
        let pic = match self.inner.get_picture() {
            Ok(pic) => pic,
            Err(Rav1dError::TryAgain) => return Ok(None),
            Err(_) => return Err(()),
        };
        if pic.bit_depth() != 8 {
            return Err(());
        }
        let width = (pic.width() as usize) & !1;
        let height = (pic.height() as usize) & !1;
        if width == 0 || height == 0 {
            return Ok(None);
        }
        let y_stride = pic.stride(PlanarImageComponent::Y) as usize;
        let y_plane = pic.plane(PlanarImageComponent::Y);
        let mut y = Vec::with_capacity(width * height);
        for row in 0..height {
            let start = row * y_stride;
            y.extend_from_slice(&y_plane[start..start + width]);
        }

        let uv_w = width / 2;
        let uv_h = height / 2;
        let (u, v) = match pic.pixel_layout() {
            PixelLayout::I420 => {
                let uv_stride = pic.stride(PlanarImageComponent::U) as usize;
                let u_plane = pic.plane(PlanarImageComponent::U);
                let v_plane = pic.plane(PlanarImageComponent::V);
                let mut u = Vec::with_capacity(uv_w * uv_h);
                let mut v = Vec::with_capacity(uv_w * uv_h);
                for row in 0..uv_h {
                    let start = row * uv_stride;
                    u.extend_from_slice(&u_plane[start..start + uv_w]);
                    v.extend_from_slice(&v_plane[start..start + uv_w]);
                }
                (u, v)
            }
            PixelLayout::I400 => (vec![128u8; uv_w * uv_h], vec![128u8; uv_w * uv_h]),
            PixelLayout::I422 => {
                let uv_stride = pic.stride(PlanarImageComponent::U) as usize;
                let u_plane = pic.plane(PlanarImageComponent::U);
                let v_plane = pic.plane(PlanarImageComponent::V);
                let mut u = Vec::with_capacity(uv_w * uv_h);
                let mut v = Vec::with_capacity(uv_w * uv_h);
                for row in 0..uv_h {
                    let start = (row * 2) * uv_stride;
                    u.extend_from_slice(&u_plane[start..start + uv_w]);
                    v.extend_from_slice(&v_plane[start..start + uv_w]);
                }
                (u, v)
            }
            PixelLayout::I444 => {
                let uv_stride = pic.stride(PlanarImageComponent::U) as usize;
                let u_plane = pic.plane(PlanarImageComponent::U);
                let v_plane = pic.plane(PlanarImageComponent::V);
                let mut u = Vec::with_capacity(uv_w * uv_h);
                let mut v = Vec::with_capacity(uv_w * uv_h);
                for row in 0..uv_h {
                    let start = (row * 2) * uv_stride;
                    for col in 0..uv_w {
                        u.push(u_plane[start + col * 2]);
                        v.push(v_plane[start + col * 2]);
                    }
                }
                (u, v)
            }
        };
        Ok(Some(Planes { y, u, v, width, height }))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn leb128_and_packet_parsing_handle_w0_and_fixed_w() {
        let mut buf = Vec::new();
        write_leb128(300, &mut buf);
        assert_eq!(read_leb128(&buf), Some((300, 2)));

        // W=2: first element has length 2, second extends to end.
        let pkt_w2 = [0x28, 0x02, 0x08, 0xaa, 0x30, 0xbb, 0xcc];
        let (agg, elems) = parse_packet(&pkt_w2).unwrap();
        assert!(!agg.z && !agg.y && agg.w == 2 && agg.n);
        assert_eq!(elems, vec![&[0x08, 0xaa][..], &[0x30, 0xbb, 0xcc][..]]);

        // W=0: every element is length-prefixed.
        let pkt_w0 = [0x08, 0x02, 0x08, 0xaa, 0x03, 0x30, 0xbb, 0xcc];
        let (agg, elems) = parse_packet(&pkt_w0).unwrap();
        assert_eq!(agg.w, 0);
        assert_eq!(elems, vec![&[0x08, 0xaa][..], &[0x30, 0xbb, 0xcc][..]]);
    }

    #[test]
    fn assembler_handles_fragmented_obus_and_gap_recovery() {
        let mut asm = Assembler::default();
        // Packetize the genuine AV1 keyframe with tiny MTU to force fragmentation (Y=1 -> Z=1).
        let pieces = packetize(SAMPLE_KEYFRAME_OBU, 10);
        assert!(pieces.len() >= 3, "expected fragmented packets, got {}", pieces.len());
        let mut out = None;
        for (i, piece) in pieces.iter().enumerate() {
            let got = asm.push(i as u16, 90_000, piece.marker, &piece.payload);
            if i + 1 == pieces.len() {
                out = got;
            } else {
                assert!(got.is_none());
            }
        }
        let assembled = out.expect("assembled AV1 temporal unit");
        assert!(is_key(&assembled));

        // Gap followed by non-N delta packet is dropped while broken.
        let delta_pkt = [0x10, 0x30, 0x20, 0x01, 0x02];
        assert!(asm.push(99, 93_000, true, &delta_pkt).is_none());

        // Next N=1 keyframe recovers cleanly.
        let pieces_whole = packetize(SAMPLE_KEYFRAME_OBU, MAX_PAYLOAD);
        assert_eq!(pieces_whole.len(), 1);
        let recovered = asm.push(100, 96_000, pieces_whole[0].marker, &pieces_whole[0].payload);
        assert!(recovered.is_some());
    }

    #[test]
    fn real_av1_keyframe_packetizes_assembles_and_decodes_to_64x48_planes() {
        let pieces = packetize(SAMPLE_KEYFRAME_OBU, 14);
        let mut asm = Assembler::default();
        let mut assembled = None;
        for (i, p) in pieces.iter().enumerate() {
            assembled = asm.push(i as u16, 90_000, p.marker, &p.payload);
        }
        let frame = assembled.expect("assembled AV1 keyframe");
        let mut dec = Av1Decoder::new().expect("av1 decoder");
        let planes = dec.decode(&frame).expect("decode ok").expect("decoded picture");
        assert_eq!((planes.width, planes.height), (64, 48));
        assert_eq!(planes.y.len(), 64 * 48);
        assert_eq!(planes.u.len(), 32 * 24);
        assert_eq!(planes.v.len(), 32 * 24);
    }
}
