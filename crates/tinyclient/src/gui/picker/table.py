#!/usr/bin/env python3
"""Writes table.rs: every fully-qualified Unicode emoji up to EMOJI_MAX, in CLDR order.

Inputs (all MIT or Unicode-licensed data files; pass their paths):
  emoji-test.txt   Unicode's list (unicode.org/Public/emoji/<v>/emoji-test.txt)
  gemoji.json      {"shortcode": "glyph"}, GitHub's names (the ones Slack and Discord also take)
  emojilib.json    emojilib 2.x emojis.json, for extra search words
Run: python3 table.py emoji-test.txt gemoji.json emojilib.json > table.rs
"""
import json, re, sys

EMOJI_MAX = 16.0
GROUPS = ["Smileys & people", "Animals & nature", "Food & drink", "Travel & places",
          "Activities", "Objects", "Symbols", "Flags"]
GROUP_OF = {"Smileys & Emotion": 0, "People & Body": 0, "Animals & Nature": 1, "Food & Drink": 2,
            "Travel & Places": 3, "Activities": 4, "Objects": 5, "Symbols": 6, "Flags": 7}
TONES = ["1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"]

test_path, gemoji_path, lib_path = sys.argv[1:4]
rows, by_codes, group = [], {}, None
for line in open(test_path, encoding="utf-8"):
    if line.startswith("# group:"):
        group = GROUP_OF.get(line.split(":", 1)[1].strip())
        continue
    m = re.match(r"^([0-9A-F ]+?)\s*; fully-qualified\s*# (\S+) E(\d+\.\d+) (.+)$", line)
    if not m or group is None:
        continue
    codes, glyph, version, name = m.group(1).split(), m.group(2), float(m.group(3)), m.group(4)
    by_codes[" ".join(codes)] = name
    if version > EMOJI_MAX or "skin tone" in name:
        continue
    rows.append((codes, glyph, group, name))

def toned(codes, tone):
    # One person: the modifier follows the first code point, in place of its FE0F.
    rest = codes[1:]
    if rest and rest[0] == "FE0F":
        rest = rest[1:]
    return [codes[0], tone] + rest

strip = lambda s: s.replace("️", "")
gemoji = json.load(open(gemoji_path, encoding="utf-8"))
names = {}
for code, glyph in gemoji.items():
    names.setdefault(strip(glyph), []).append(code)
lib = json.load(open(lib_path, encoding="utf-8"))
keywords = {}
for code, entry in lib.items():
    words = keywords.setdefault(strip(entry["char"]), [])
    words += [code] + [w for w in entry.get("keywords", []) if re.fullmatch(r"[a-z0-9_+\-]+", w)]

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

out = ["// @generated by table.py from Unicode's emoji-test.txt (Emoji %s), GitHub's gemoji" % EMOJI_MAX,
       "// shortcodes and emojilib keywords. Do not edit by hand.", "",
       "use super::emoji::Emoji;", "",
       "pub const GROUPS: [&str; %d] = [%s];" % (len(GROUPS), ", ".join('"%s"' % g for g in GROUPS)), "",
       "pub static EMOJI: &[Emoji] = &["]
for codes, glyph, group, name in rows:
    tones = all(" ".join(toned(codes, t)) in by_codes for t in TONES)
    found = names.get(strip(glyph), [])
    # Some name lists carry truncated copies ("tad" beside "tada"): a name that only begins
    # another of the same glyph is dropped.
    shortcodes = [c for c in found if not any(o != c and o.startswith(c) for o in found)]
    plain = sorted([c for c in shortcodes if re.fullmatch(r"[a-z_]+", c)], key=lambda c: (len(c), c))
    cldr = re.sub(r"[^\w]+", "_", name.lower().replace("flag: ", "")).strip("_")
    code = plain[0] if plain else (shortcodes[0] if shortcodes else cldr)
    words = []
    for w in [code] + shortcodes + re.findall(r"[\w]+", name.lower()) + keywords.get(strip(glyph), []):
        w = w.lower()
        if w not in words and len(words) < 10:
            words.append(w)
    out.append('    Emoji { glyph: "%s", group: %d, tones: %s, code: "%s", words: "%s" },'
               % (esc(glyph), group, "true" if tones else "false", esc(code), esc(" ".join(words))))
out.append("];")
print("\n".join(out))
